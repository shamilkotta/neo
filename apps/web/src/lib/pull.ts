export function puller(run: () => Promise<void>) {
  let running: Promise<void> | undefined;
  let again = false;
  return () => {
    if (running) {
      again = true;
      return running;
    }
    running = (async () => {
      do {
        again = false;
        await run();
      } while (again);
    })().finally(() => {
      running = undefined;
    });
    return running;
  };
}
